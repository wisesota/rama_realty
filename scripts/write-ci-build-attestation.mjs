import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { pnpmInvocation } from "./pnpm-runtime.mjs";

function argumentValue(name, fallback) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : fallback;
}

if (process.env.CI !== "true" || process.env.GITHUB_ACTIONS !== "true") {
  throw new Error("CI build attestations can only be generated by GitHub Actions.");
}

const repository = process.env.GITHUB_REPOSITORY?.trim() ?? "";
const runId = process.env.GITHUB_RUN_ID?.trim() ?? "";
const githubToken = process.env.GITHUB_TOKEN?.trim() ?? "";
const apiUrl = process.env.GITHUB_API_URL?.trim() || "https://api.github.com";
if (!/^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/.test(repository) || !/^\d+$/.test(runId) || !githubToken) {
  throw new Error("CI attestation refused because authenticated workflow evidence is unavailable.");
}
if (process.env.GITHUB_WORKFLOW !== "CI" || process.env.GITHUB_JOB !== "attestation") {
  throw new Error("CI attestation refused outside the dedicated attestation job.");
}
if (process.env.GITHUB_EVENT_NAME !== "push" || process.env.GITHUB_REF !== "refs/heads/main") {
  throw new Error("CI attestation refused outside a protected main-branch push.");
}

const jobsResponse = await fetch(`${apiUrl}/repos/${repository}/actions/runs/${runId}/jobs?filter=latest&per_page=100`, {
  headers: {
    Accept: "application/vnd.github+json",
    Authorization: `Bearer ${githubToken}`,
    "X-GitHub-Api-Version": "2022-11-28",
  },
});
if (!jobsResponse.ok) {
  throw new Error(`CI attestation refused because workflow evidence returned HTTP ${jobsResponse.status}.`);
}
const workflowEvidence = await jobsResponse.json();
const jobs = Array.isArray(workflowEvidence?.jobs) ? workflowEvidence.jobs : [];
const requiredJobs = ["dependency-integrity", "quality"];
const verifiedJobs = Object.fromEntries(requiredJobs.map((name) => {
  const job = jobs.find((candidate) => candidate?.name === name);
  if (job?.status !== "completed" || job?.conclusion !== "success") {
    throw new Error(`CI attestation refused because ${name} lacks authenticated success evidence.`);
  }
  return [name, {
    id: job.id,
    conclusion: job.conclusion,
    completedAt: job.completed_at,
    htmlUrl: job.html_url,
  }];
}));

const root = process.cwd();
const outputPath = resolve(root, argumentValue("--output", "artifacts/ci-build-attestation.json"));
const commit = execFileSync("git", ["rev-parse", "HEAD"], { cwd: root, encoding: "utf8" }).trim();
const status = execFileSync("git", ["status", "--porcelain"], { cwd: root, encoding: "utf8" }).trim();
const expectedCommit = process.env.RAMA_RELEASE_COMMIT?.trim() ?? "";
const lockfile = readFileSync(resolve(root, "pnpm-lock.yaml"), "utf8").replace(/\r\n/g, "\n");
const lockfileSha256 = createHash("sha256").update(lockfile, "utf8").digest("hex");
const pnpmCommand = pnpmInvocation(["--version"]);
const pnpmVersion = execFileSync(pnpmCommand.command, pnpmCommand.args, { cwd: root, encoding: "utf8" }).trim();

if (status) {
  throw new Error(`CI attestation refused because the checkout is dirty:\n${status}`);
}
if (!/^[a-f0-9]{40}$/.test(expectedCommit) || expectedCommit !== commit) {
  throw new Error("CI attestation refused because RAMA_RELEASE_COMMIT does not match HEAD.");
}

const attestation = {
  schemaVersion: 1,
  evidenceAuthority: "github-actions",
  releaseCommit: commit,
  lockfileSha256,
  generatedAt: new Date().toISOString(),
  toolchain: {
    node: process.versions.node,
    pnpm: pnpmVersion,
  },
  workflow: {
    repository,
    runId,
    runAttempt: process.env.GITHUB_RUN_ATTEMPT ?? null,
    workflowRef: process.env.GITHUB_WORKFLOW_REF ?? null,
  },
  gates: {
    dependencyIntegrity: verifiedJobs["dependency-integrity"],
    quality: verifiedJobs.quality,
  },
};

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, `${JSON.stringify(attestation, null, 2)}\n`, { flag: "wx" });
console.log(JSON.stringify({ ok: true, output: outputPath, releaseCommit: commit, lockfileSha256 }));
